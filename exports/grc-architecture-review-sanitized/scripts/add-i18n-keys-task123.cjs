/**
 * One-shot script: extend en.json and ar.json with the keys needed by
 * Task #123 (translate dashboard table headers, modals, and form fields).
 *
 * Designed to be idempotent — re-running won't change values that are
 * already present and won't reorder existing keys.
 *
 * Run: node scripts/add-i18n-keys-task123.cjs
 */
const fs = require('fs');
const path = require('path');

const I18N_DIR = path.join(__dirname, '..', 'dashboard', 'i18n');
const EN_PATH = path.join(I18N_DIR, 'en.json');
const AR_PATH = path.join(I18N_DIR, 'ar.json');

const EN = JSON.parse(fs.readFileSync(EN_PATH, 'utf8'));
const AR = JSON.parse(fs.readFileSync(AR_PATH, 'utf8'));

function merge(target, additions) {
  Object.keys(additions).forEach(function (k) {
    if (target[k] === undefined) target[k] = additions[k];
  });
}

